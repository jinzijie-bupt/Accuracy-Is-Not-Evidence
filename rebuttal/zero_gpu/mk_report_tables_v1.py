#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""mk_report_tables_v1.py -- renders the markdown tables used in REPORT_A3_QJ.md from the two result JSONs
(qc_qj_p5n_v1.json, qj_gamma_strata_v1.json).  No new computation; every cell is copied from those files.
Output: report_tables_v1.md (records the sha16 of both JSONs)."""
import os, json, hashlib
LOCAL_ROOT = os.environ.get("LOCAL_ROOT", ".")  # analysis directory holding the pulled result files (results/, rebuttal/)

HERE = os.path.dirname(os.path.abspath(__file__))
A = os.path.join(HERE, "qc_qj_p5n_v1.json")
G = os.path.join(HERE, "qj_gamma_strata_v1.json")


def sha16(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()[:16]


def ci(s, sc=100.0, fmt="%+.1f"):
    if not s or s.get("est") is None:
        return "n/a"
    lo, hi = s["ci95"]
    return (fmt + " [" + fmt + ", " + fmt + "]") % (sc * s["est"], sc * lo, sc * hi)


def p3(x):
    return "n/a" if x is None else "%.3f" % x


NAMES = {"Qwen7B_a05_node5": "Qwen-7B placebo-controlled α=0.5", "Qwen7B_SFT_node5": "Qwen-7B SFT", "Qwen7B_mDPO_node5": "Qwen-7B mDPO-style",
         "Qwen7B_IoUGRPO_node1": "Qwen-7B IoU-GRPO", "Qwen7B_ablsingle_node1": "Qwen-7B abl_single (ablation)",
         "TZ_a05_node5_evaltf": "TimeZero α=0.5 (vf train / tf eval)", "TZ_a05_node2_vf": "TimeZero α=0.5(vf)",
         "TZ_a05trtf_node2_tf": "TimeZero α=0.5 (tf train / tf eval)", "TR1_a025_node5": "Time-R1 α=0.25",
         "VC_a05_node5_evaltf": "VideoChat-R1 α=0.5 (vf train / tf eval)", "VC_a05_node4_vf": "VideoChat-R1 α=0.5(vf)"}


def main():
    a = json.load(open(A, encoding="utf-8")); g = json.load(open(G, encoding="utf-8"))
    L = ["<!-- generated by mk_report_tables_v1.py from qc_qj_p5n_v1.json sha16=%s and qj_gamma_strata_v1.json sha16=%s -->" % (sha16(A), sha16(G)), ""]
    # T1: QC1 answered subset
    L += ["### Table C1-a Evidence share 1−aE/aO where both sides give a span (J_all: base and arm parseable under all three conditions clean/E/O)", "",
          "| pair | machine | edit | coverage under E base/arm | n(J_all) | base share | arm share | Δshare (pts) [95%] | Δshare over all 1000 questions (pts) |",
          "|---|---|---|---|---|---|---|---|---|"]
    for pid, pr in a["pairs"].items():
        for ax in ("mask", "swap"):
            r = pr["QC1_answered_subset"][ax]; j = r["J_all"]
            # all-question share from R@0.5_by_op
            def sh(t):
                e, o = pr["R@0.5_by_op"][t]["%s_evid" % ax], pr["R@0.5_by_op"][t]["%s_rand" % ax]
                return 1 - e / o
            full = 100 * (sh("arm") - sh("base"))
            if "base" not in j:
                L.append("| %s | %s | %s | %.3f/%.3f | %d | n/a | n/a | n/a | %+.1f |" % (NAMES[pid], pr["machine"], ax, r["coverage_E"]["base"], r["coverage_E"]["arm"], j["n"], full)); continue
            s = j["evidence_share_1_minus_aE_over_aO"]
            L.append("| %s | %s | %s | %.3f/%.3f | %d | %s | %s | %s | %+.1f |" % (
                NAMES[pid], pr["machine"], ax, r["coverage_E"]["base"], r["coverage_E"]["arm"], j["n"],
                ci(s["base"]), ci(s["arm"]), ci(s["delta_pts"], 1.0), full))
    L += ["", "### Table C1-b R@0.5 and mIoU under E (arm − base) where both sides give a span under E (J_E)", "",
          "| pair | edit | n(J_E) | clean R@0.5 base/arm | R@0.5 under E base/arm | ΔR@0.5_E (pts) | ΔmIoU_E | difference in (clean−E) drop arm−base (pts) |", "|---|---|---|---|---|---|---|---|"]
    for pid, pr in a["pairs"].items():
        for ax in ("mask", "swap"):
            j = pr["QC1_answered_subset"][ax]["J_E"]
            if "base" not in j:
                continue
            L.append("| %s | %s | %d | %.3f/%.3f | %.3f/%.3f | %s | %s | %s |" % (
                NAMES[pid], ax, j["n"], j["base"]["R@0.5_clean"], j["arm"]["R@0.5_clean"], j["base"]["R@0.5_E"], j["arm"]["R@0.5_E"],
                ci(j["delta_R@0.5_E_arm_minus_base"]), ci(j["delta_mIoU_E_arm_minus_base"], 1.0, "%+.3f"),
                ci(j["drop_clean_minus_E"]["delta_arm_minus_base"])))
    # T2: QC2 refusal by condition (all questions)
    ops = ("none", "mask_evid", "mask_rand", "swap_evid", "swap_rand", "black")
    L += ["", "### Table C2-a No-span (unparsed) rate per condition, all 1000 questions", "",
          "| pair | model | clean | mask-E | mask-O | swap-E | swap-O | all black | of which strict refusal (There are none.) mask-E / swap-E |", "|---|---|---|---|---|---|---|---|---|"]
    for pid, pr in a["pairs"].items():
        q = pr["QC2_refusal"]["per_condition"]
        for t in ("base", "arm"):
            L.append("| %s | %s | %s | %s/%s |" % (NAMES[pid], t, " | ".join(p3(q[o][t]["unparsed"]) for o in ops),
                                                p3(q["mask_evid"][t]["strict"]), p3(q["swap_evid"][t]["strict"])))
    L += ["", "### Table C2-b Edit-induced no-span rate (only questions where base and arm both give a span under clean), E−O and arm−base DiD (pts)", "",
          "| pair | n | model | mask-E | mask-O | swap-E | swap-O | mask E−O | swap E−O | mask DiD | swap DiD |", "|---|---|---|---|---|---|---|---|---|---|---|"]
    for pid, pr in a["pairs"].items():
        b = pr["QC2_refusal"]["on_clean_answered_both"]
        if "rates" not in b:
            continue
        for t in ("base", "arm"):
            r = b["rates"][t]
            L.append("| %s | %d | %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                NAMES[pid], b["n"], t, p3(r["mask_evid"]), p3(r["mask_rand"]), p3(r["swap_evid"]), p3(r["swap_rand"]),
                ci(b["mask"]["%s_E_minus_O" % t]), ci(b["swap"]["%s_E_minus_O" % t]),
                ci(b["mask"]["DiD_arm_minus_base"]) if t == "arm" else "", ci(b["swap"]["DiD_arm_minus_base"]) if t == "arm" else ""))
    L += ["", "### Table C2-c Definition of paper Table 20 left column (on questions answered correctly under each side O, share that becomes no-span / wrong-span under E, arm−base, pts)", "",
          "| pair | mask no span | mask wrong span | swap no span (new) | swap wrong span (new) |", "|---|---|---|---|---|"]
    for pid, pr in a["pairs"].items():
        Lb = pr["QC2_lost_answers_T20style"]
        L.append("| %s | %s | %s | %s | %s |" % (NAMES[pid], ci(Lb["mask"]["delta_no_interval_pts"], 1.0), ci(Lb["mask"]["delta_wrong_interval_pts"], 1.0),
                                                ci(Lb["swap"]["delta_no_interval_pts"], 1.0), ci(Lb["swap"]["delta_wrong_interval_pts"], 1.0)))
    # T3: QJ behaviour
    sd = a["strata_definition"]
    L += ["", "### Table J-a Behavioral audit stratified by prior solvability: Δevidence share (arm−base, pts)", "",
          "Prior strata: const = constant window (0,10) s has IoU≥0.5 with annotation (n=%d/1000); blind = at least one of 6 base outputs (tm) hits on all-black video (n=%d/1000); overlap %d." % (
              sd["const"]["n_prior"], sd["blind"]["n_prior"], sd["overlap_const_and_blind"]), "",
          "| pair | edit | stratum | prior-solvable n / Δshare | non-prior-solvable n / Δshare | interaction DiD (prior − non-prior, pts) |", "|---|---|---|---|---|---|"]
    for pid, pr in a["pairs"].items():
        for ax in ("mask", "swap"):
            for s in ("const", "blind"):
                blk = pr["QJ_prior_strata"][s]; P = blk["prior_solvable"]; N = blk["not_prior_solvable"]
                L.append("| %s | %s | %s | %d / %s | %d / %s | %s |" % (NAMES[pid], ax, s, P["n"], ci(P[ax]["delta_share_pts"], 1.0), N["n"],
                                                                     ci(N[ax]["delta_share_pts"], 1.0), ci(blk["interaction_DiD_prior_minus_notprior_pts"][ax], 1.0)))
    # T4: QJ gamma
    L += ["", "### Table J-b Likelihood audit Γ (nats/token) stratified by prior solvability (H∩ cohort of the 200 audit questions)", "",
          "| row | machine | edit | stratum | Γ all (n) | Γ prior-solvable (n) | Γ non-prior-solvable (n) | interaction (prior − non-prior) |", "|---|---|---|---|---|---|---|---|"]
    for r in g["rows"]:
        for op in ("mask", "swap"):
            o = r["ops"][op]
            for s in ("const", "blind"):
                S = o["strata"][s]
                L.append("| %s | %s | %s | %s | %s (%d) | %s (%d) | %s (%d) | %s |" % (
                    r["row"], r["machine"], op, s, ci(o["Gamma_all"], 1.0, "%+.2f"), r["n_cohort"],
                    ci(S["prior_solvable"], 1.0, "%+.2f"), S["n_prior"], ci(S["not_prior_solvable"], 1.0, "%+.2f"), S["n_notprior"],
                    ci(S.get("interaction_prior_minus_not"), 1.0, "%+.2f")))
    # inputs
    L += ["", "### Input files (sha256[:16])", "", "| key | sha16 | meta sha16 | file |", "|---|---|---|---|"]
    for k, v in a["inputs"].items():
        L.append("| %s | %s | %s | %s |" % (k, v["sha16"], v["meta_sha16"], v["file"].replace((LOCAL_ROOT + "/results/"), "results/")))
    for r in g["rows"]:
        L.append("| Γ:%s | %s | — | %s |" % (r["row"], r["gamma_file_sha16"], r["gamma_file"].replace((LOCAL_ROOT + "/results/"), "results/")))
        for x in r["raw_inputs"]:
            L.append("| ↳ 14Ln %s | %s | — | %s (exists and sha matches: %s) |" % (x["role"], x["sha16_recorded"], x["file"].replace((LOCAL_ROOT + "/results/"), "results/"), x["exists_and_matches"]))
    open(os.path.join(HERE, "report_tables_v1.md"), "w", encoding="utf-8").write("\n".join(L) + "\n")
    print("ok")


if __name__ == "__main__":
    main()
