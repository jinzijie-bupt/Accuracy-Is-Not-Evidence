def parse_ops_v2(value: str | Sequence[str]) -> list[str]:
    raw = value.split(",") if isinstance(value, str) else value
    ops = list(dict.fromkeys(str(x).strip() for x in raw if str(x).strip()))
    banned = [op for op in ops if op in HELD_OUT_OPS]
    if banned:
        raise ValueError(
            f"held-out operators must never be trained: {banned}; "
            "they are the certificate's extrapolation targets"
        )
    unknown = [op for op in ops if op not in SUPPORTED_V2]
    if unknown:
        raise ValueError(f"unsupported v2 training operators {unknown}; supported={list(SUPPORTED_V2)}")
    if not ops:
        raise ValueError("at least one operator is required")
    return ops


def _stable_rng(seed: int, epoch: int, row_index: int, op: str, tag: str) -> random.Random:
    digest = hashlib.sha256(f"{seed}|{epoch}|{row_index}|{op}|{tag}".encode()).digest()
    return random.Random(int.from_bytes(digest[:8], "big"))


def _stable_tiebreak(seed: int, epoch: int, row_index: int, op: str) -> str:
    return hashlib.sha256(f"{seed}|{epoch}|{row_index}|{op}".encode("utf-8")).hexdigest()


# ---------------------------------------------------------------- validity


def valid_ops_v2(row: Mapping[str, object], requested: Sequence[str], *, query_group_key: str) -> list[str]:
    """QC validity + |E*|>=2 guard for shuffle.

    Base semantics from qcdro_objective_draft.valid_ops_for_row:
      shuffle/reverse are valid only if the query is in TEMPORAL_QUERY_GROUPS or row['shuffle_valid'];
      for other queries they are preserving controls (go to invariance/SFT, not PAPO).
    v2 addition: |E*|<2 makes the within-group permutation the identity ⇒ fake intervention, marked invalid.
    """
    ops = valid_ops_for_row(dict(row), requested, query_group_key=query_group_key)
    n_estar = int(row.get("n_estar", len(row.get("estar", []) or [])))
    if n_estar < 2:
        ops = [op for op in ops if op not in ("shuffle", "reverse")]
    return ops


def group_of(row: Mapping[str, object], op: str, *, scheme: str, query_group_key: str) -> str:
    if scheme == "product":
        return f"{str(row.get(query_group_key, 'generic_action'))}/{op}"
    if scheme == "validity":
        temporal = bool(row.get("shuffle_valid", False)) or str(
            row.get(query_group_key, "generic_action")
        ) in TEMPORAL_QUERY_GROUPS
        return f"{'tvalid' if temporal else 'tinvalid'}/{op}"
    raise ValueError(f"unknown group scheme: {scheme}")


# ---------------------------------------------------------------- schedule


@dataclass(frozen=True)
class ItemV2:
    epoch: int
    row_index: int
    ops: tuple[str, ...]

    def as_dict(self) -> dict[str, object]:
        return {"epoch": self.epoch, "row_index": self.row_index, "ops": list(self.ops)}


@dataclass(frozen=True)
class ScheduleV2:
    items: tuple[ItemV2, ...]
    fingerprint: str
    exposure: dict[str, int]
    skipped_too_few_valid: int
    rows_with_explicit_validity: int
    rows_with_query_group: int

    def as_summary(self) -> dict[str, object]:
        return {
            "examples": len(self.items),
            "fingerprint": self.fingerprint,
            "operator_exposure": dict(self.exposure),
            "skipped_too_few_valid": self.skipped_too_few_valid,
            "rows_with_explicit_validity": self.rows_with_explicit_validity,
            "rows_with_query_group": self.rows_with_query_group,
        }


def build_schedule_v2(
    rows: Sequence[Mapping[str, object]],
    *,
    epochs: int,
    requested_ops: Sequence[str],
    ops_per_example: int,
    seed: int,
    query_group_key: str,
) -> ScheduleV2:
    """**Same algorithm** as 26_/helpers.build_fair_schedule (least-exposed first + stable hash tie-break),
    only the valid check is replaced by valid_ops_v2 (with the shuffle guard).

    The schedule carries no grouping info ⇒ mean arm and qcdro arm fingerprints are necessarily identical.
    """
    requested = parse_ops_v2(requested_ops)
    if epochs <= 0:
        raise ValueError("epochs must be positive")
    if not 1 <= ops_per_example <= len(requested):
        raise ValueError("ops_per_example must be in [1, len(requested_ops)]")

    exposure: Counter[str] = Counter({op: 0 for op in requested})
    items: list[ItemV2] = []
    skipped = 0
    for epoch in range(epochs):
        order = list(range(len(rows)))
        random.Random(1234 + epoch + 1000 * seed).shuffle(order)
        for row_index in order:
            valid = valid_ops_v2(rows[row_index], requested, query_group_key=query_group_key)
            if len(valid) < ops_per_example:
                skipped += 1
                continue
            ranked = sorted(
                valid,
                key=lambda op: (exposure[op], _stable_tiebreak(seed, epoch, row_index, op)),
            )
            chosen = tuple(ranked[:ops_per_example])
            exposure.update(chosen)
            items.append(ItemV2(epoch, row_index, chosen))

    digest = hashlib.sha256()
    for item in items:
        digest.update(
            (json.dumps(item.as_dict(), sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")
        )
    return ScheduleV2(
        items=tuple(items),
        fingerprint=digest.hexdigest(),
        exposure={op: int(exposure[op]) for op in requested},
        skipped_too_few_valid=skipped,
        rows_with_explicit_validity=sum(1 for r in rows if "valid_ops" in r),
        rows_with_query_group=sum(1 for r in rows if query_group_key in r),
    )


def group_exposure(
    schedule: ScheduleV2,
    rows: Sequence[Mapping[str, object]],
    *,
    scheme: str,
    query_group_key: str,
) -> dict[str, int]:
    c: Counter[str] = Counter()
    for item in schedule.items:
        row = rows[item.row_index]
        for op in item.ops:
            c[group_of(row, op, scheme=scheme, query_group_key=query_group_key)] += 1
    return dict(sorted(c.items(), key=lambda kv: -kv[1]))


