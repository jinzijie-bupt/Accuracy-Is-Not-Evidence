def native_decode(video_path: str, args):
    """fps-sampled, smart-resized frames exactly as qwen_vl_utils feeds the native evaluator.
    Returns (frames uint8 (T,H,W,3), times[s] per frame, duration[s], sample_fps)."""
    from qwen_vl_utils import fetch_video
    ele = {
        "type": "video", "video": video_path, "fps": float(args.fps),
        "total_pixels": int(args.total_pixels), "min_pixels": int(args.min_pixels),
        "max_frames": int(args.max_frames),
    }
    (vid, meta), sample_fps = fetch_video(ele, image_patch_size=int(getattr(args, "image_patch_size", 14)), return_video_sample_fps=True, return_video_metadata=True)
    fr = vid.round().clamp(0, 255).to(torch.uint8).permute(0, 2, 3, 1).contiguous().cpu().numpy()
    vfps = float(meta.get("fps") or 0.0) or float(args.fps)
    idx = list(meta.get("frames_indices") or range(fr.shape[0]))
    times = [float(i) / vfps for i in idx]
    total = float(meta.get("total_num_frames") or len(idx))
    dur = total / vfps if vfps > 0 else float(len(idx)) / float(sample_fps)
    return fr, times, dur, float(sample_fps)


_PROC_MODE = {"mode": None}
_TEXT_FIRST = {"on": False}  # r3: --text-first (message order text->video)


def _native_inputs(proc, text: str, vid: torch.Tensor, sample_fps: float):
    """tf5: video_metadata + do_sample_frames=False (12p4n_tf5meta path); tf4.51: fps list (TimeZero evaluate.py path)."""
    T = int(vid.shape[0])
    meta = [{"fps": float(sample_fps), "total_num_frames": T, "duration": T / float(sample_fps),
             "frames_indices": list(range(T)), "video_backend": "decord"}]
    mode = _PROC_MODE["mode"]
    first = mode is None
    if first:  # r2: transformers<5 silently IGNORES video_metadata/do_sample_frames (no TypeError) -> choose by version
        import transformers as _tf
        if int(str(_tf.__version__).split(".")[0]) < 5:
            mode = _PROC_MODE["mode"] = "tf4fps"
            print(f"[native] transformers {_tf.__version__} <5: fps-list path (video_metadata is ignored there)", flush=True)
    if mode in (None, "tf5meta"):
        try:
            out = proc(text=[text], videos=[vid], video_metadata=meta, do_sample_frames=False,
                       padding=True, return_tensors="pt")
            if mode is None:
                _PROC_MODE["mode"] = "tf5meta"
                print(f"[native] processor mode=tf5meta second_per_grid_ts={out.get('second_per_grid_ts')} "
                      f"video_grid_thw={out.get('video_grid_thw')}", flush=True)
            return out
        except TypeError as exc:
            if mode == "tf5meta":
                raise
            print(f"[native] tf5meta kwargs rejected ({exc}); falling back to fps list (tf4 path)", flush=True)
            _PROC_MODE["mode"] = "tf4fps"
    out = proc(text=[text], videos=[vid], fps=[float(sample_fps)], padding=True, return_tensors="pt")
    if first:
        print(f"[native] processor mode=tf4fps second_per_grid_ts={out.get('second_per_grid_ts')} "
              f"video_grid_thw={out.get('video_grid_thw')}", flush=True)
    return out


def native_completion_logprob(model, proc, frames_np, sample_fps, prompt_text, completion, device, cache):
    """(sum log p of completion tokens, n tokens) through the native videos= path. cache: per-example dict
    holding the chat-template text and prompt length (identical across clean/edited frames of one example)."""
    vid = torch.from_numpy(np.ascontiguousarray(frames_np)).permute(0, 3, 1, 2)  # (T,3,H,W) uint8
    if "text" not in cache:
        _vp = {"type": "video", "video": "native_placeholder"}; _tp = {"type": "text", "text": prompt_text}
        msgs = [{"role": "user", "content": ([_tp, _vp] if _TEXT_FIRST["on"] else [_vp, _tp])}]  # r3
        cache["text"] = proc.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
        cache["plen"] = int(_native_inputs(proc, cache["text"], vid, sample_fps).input_ids.shape[1])
    full = _native_inputs(proc, cache["text"] + completion, vid, sample_fps).to(device)
    plen = cache["plen"]
    out = model(**full)
    logits = out.logits[:, :-1, :].float()
    labels = full.input_ids[:, 1:]
    logp = torch.log_softmax(logits, dim=-1).gather(-1, labels.unsqueeze(-1)).squeeze(-1)
    seg = logp[:, plen - 1:]
    return seg.sum(), seg.shape[1]


def _prepare_example(model, proc, ex, device, args):
    caption = str(ex["caption"])
    gs, ge = float(ex["gs"]), float(ex["ge"])
    frames, times, duration, sfps = native_decode(os.path.join(base.VIDEO_DIR, str(ex["video"])), args)
    estar = np.asarray([i for i, t in enumerate(times) if gs - 1e-6 <= t <= ge + 1e-6], dtype=int)
    if len(estar) == 0:
        j = int(np.argmin([abs(t - 0.5 * (gs + ge)) for t in times]))
        estar = np.asarray([j], dtype=int)
    if len(estar) >= len(frames) - 1:
        raise ValueError(f"degenerate evidence set |E*|={len(estar)} T={len(frames)}")
    donor_frames, _, _, _ = native_decode(os.path.join(base.VIDEO_DIR, str(ex["distractor"])), args)
    if donor_frames.shape[1:3] != frames.shape[1:3]:
        H, W = int(frames.shape[1]), int(frames.shape[2])
        donor_frames = np.stack([cv2.resize(np.ascontiguousarray(f), (W, H)) for f in donor_frames])
    completion = native_completion(gs, ge, args.answer_style)
    prompt_text = NATIVE_PROMPTS[args.prompt_style].format(caption)
    cache: dict = {}

    def completion_logp(fr: np.ndarray):
        return native_completion_logprob(model, proc, fr, sfps, prompt_text, completion, device, cache)

    return frames, estar, donor_frames, completion_logp


def _train_scheduled_example(
    model, proc, ex, *, epoch, row_index, ops, dro, device, args, group_names
):
    """Same structure as 26_._train_scheduled_example; only two differences:
    (a) operators go through corrupt_op_v2 (shuffle uses a keyed rng);
    (b) aggregation weights and DRO stats are indexed by **product group name**, not op name.
    """
    frames, estar, donor_frames, completion_logp = _prepare_example(model, proc, ex, device, args)
    clean_score, clean_tokens = completion_logp(frames)
    with torch.no_grad(), model.disable_adapter():
        ref_clean, _ = completion_logp(frames)

    groups = [group_names[op] for op in ops]
    aggregation = conditional_aggregation_weights(groups, objective=args.objective, dro=dro)

    clean_gradient = torch.zeros_like(clean_score)
    group_losses: dict[str, float] = {}
    group_margins: dict[str, float] = {}
    reported_total = 0.0
    grad_scale = 1.0 / args.accum

    for op in ops:
        g = group_names[op]
        op_rng = _stable_rng(args.seed, epoch, row_index, op, "shufperm")
        corrupt_e = corrupt_op_v2(frames, estar, donor_frames, op, rng=op_rng)
        corrupt_score, _ = completion_logp(corrupt_e)
        with torch.no_grad(), model.disable_adapter():
            ref_corrupt, _ = completion_logp(corrupt_e)

        nonevidence_score = None
        ref_nonevidence = None
        if args.npole:
            local_rng = _stable_rng(args.seed, epoch, row_index, op, "npole")
            nonevidence_idx = base._rand_nonev(estar, len(frames), local_rng)
            n_rng = _stable_rng(args.seed, epoch, row_index, op, "shufperm_n")
            corrupt_n = corrupt_op_v2(frames, nonevidence_idx, donor_frames, op, rng=n_rng)
            nonevidence_score, _ = completion_logp(corrupt_n)
            with torch.no_grad(), model.disable_adapter():
                ref_nonevidence, _ = completion_logp(corrupt_n)

        def build_loss(clean_proxy: torch.Tensor) -> torch.Tensor:
            margin = args.beta * ((clean_proxy - ref_clean) - (corrupt_score - ref_corrupt))
            value = F.softplus(-margin)
            if args.npole:
                assert nonevidence_score is not None and ref_nonevidence is not None
                if args.npole_symmetric:
                    margin_n = args.beta * (
                        (clean_proxy - ref_clean) - (nonevidence_score - ref_nonevidence)
                    )
                else:
                    margin_n = args.beta * (
                        (nonevidence_score - ref_nonevidence) - (corrupt_score - ref_corrupt)
                    )
                value = value + F.softplus(-margin_n)
                if args.rand_hinge > 0:
                    # v3sel: linear hinge on the part of the token-mean RAND drop (arm) exceeding ratio×(base drop)+slack
                    tok = float(max(1, clean_tokens))
                    drop_rand_arm = (clean_proxy - nonevidence_score) / tok
                    drop_rand_base = (ref_clean - ref_nonevidence) / tok
                    excess = drop_rand_arm - (args.rand_ratio * drop_rand_base + args.rand_slack)
                    value = value + args.rand_hinge * F.relu(excess)
            return value

        weight = aggregation[g]
        detached_loss, proxy_gradient = backward_one_with_clean_proxy(
            clean_score, build_loss, weight=weight * grad_scale
        )
        clean_gradient = clean_gradient + proxy_gradient
        group_losses[g] = float(detached_loss.float().cpu())
        primary_margin = args.beta * (
            (clean_score.detach() - ref_clean) - (corrupt_score.detach() - ref_corrupt)
        )
        group_margins[g] = float(primary_margin.float().cpu())
        reported_total += weight * group_losses[g]

    clean_nll = float((-clean_score.detach() / max(1, clean_tokens)).float().cpu())
    if args.alpha > 0:
        clean_gradient = clean_gradient + torch.full_like(
            clean_score, -args.alpha * grad_scale / max(1, clean_tokens)
        )
        reported_total += args.alpha * clean_nll
    clean_score.backward(clean_gradient)

    return {
        "loss": reported_total,
        "clean_nll": clean_nll,
        "group_losses": group_losses,
        "group_margins": group_margins,
        "aggregation_weights": aggregation,
    }


def _fp_dtype_compat(cls, path, **kw):
    """tf5 takes dtype=, tf4.51 takes torch_dtype= (same value). Fall back only on a dtype TypeError."""
    import torch as _t
    try:
        return cls.from_pretrained(path, dtype=_t.bfloat16, **kw)
    except TypeError as e:
        if "dtype" not in str(e):
            raise
        print("[dtype-compat] falling back to torch_dtype=: %s" % e, flush=True)
        return cls.from_pretrained(path, torch_dtype=_t.bfloat16, **kw)


