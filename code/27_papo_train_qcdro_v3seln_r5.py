def corrupt_op_v2(
    frames: np.ndarray,
    idx: np.ndarray,
    donor_frames: np.ndarray,
    op: str,
    *,
    rng: random.Random,
) -> np.ndarray:
    """v2 operators. shuffle is implemented locally (copied from probe apply_op); others delegate to 18_.corrupt_op."""
    if op != "shuffle":
        # The keyed donor video resolution may differ from the main video (Charades frame heights vary, e.g. 270 vs 360).
        # base.corrupt_op swap does `f[idx]=donor[:n]`, which fails to broadcast -> the whole example is skipped.
        # Resize donor to main video H×W (swap semantics = replace evidence frames with unrelated video content; scaling keeps it 'unrelated').
        if donor_frames.shape[1:3] != frames.shape[1:3]:
            import cv2
            H, W = int(frames.shape[1]), int(frames.shape[2])
            donor_frames = np.stack(
                [cv2.resize(np.ascontiguousarray(fr), (W, H)) for fr in donor_frames]
            )
        return base.corrupt_op(frames, idx, donor_frames, op)

    idx = np.asarray(idx, dtype=int)
    if len(idx) < 2:
        # Already excluded upstream by valid_ops_v2; reaching here means schedule and guard disagree -> fail fast instead of a silent fake intervention
        raise ValueError(f"shuffle needs |E*|>=2, got {len(idx)}")
    f = frames.copy()
    perm = list(idx)
    for _ in range(64):                      # keyed derangement: force non-identity
        rng.shuffle(perm)
        if any(int(p) != int(i) for p, i in zip(perm, idx)):
            break
    else:                                     # Last-resort fallback: reverse directly (|idx|>=2 is never the identity)
        perm = list(idx)[::-1]
    f[idx] = frames[np.asarray(perm, dtype=int)]
    return f


