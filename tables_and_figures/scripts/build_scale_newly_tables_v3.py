_SUPP = _os_supp.path.abspath(_os_supp.path.join(_os_supp.path.dirname(_os_supp.path.abspath(__file__)), "..", "..")).replace("\\", "/")
import hashlib, json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from canonical_v3 import Canon, M, key_str, Q7, Q3, TZ, TR, VC, TL, PEND  # noqa: E402
from canonical_v2 import _train_tf  # noqa: E402
from table_emph_v3 import emph  # noqa: E402  (bold: the entries discussed in the text; located by row label and column)

ROOT = os.path.abspath(os.path.join(HERE, ".."))
T = os.path.join(ROOT, "tables")
ANA = os.path.join(_SUPP, "readers", "derived")
LOGD = os.path.join(T, "_v3_logs")
DS_LAB = {"charades-sta": "STA", "charades-timelens": "C-TL", "qvhighlights": "QVH"}
FAMS = {Q7: "Qwen2.5-VL-7B", Q3: "Qwen2.5-VL-3B", TZ: "TimeZero", TR: "Time-R1", VC: "VideoChat-R1", TL: "TimeLens-8B"}
OBJ = {"sft": "SFT", "iou-grpo": "IoU-GRPO", "grouped-nodro": "grouped, no group wts",
       "grouped-nohinge": "grouped, no hinge", "grouped-uniform-nohinge": "grouped, no hinge, no group wts",
       "single-margin": "evidence margin only", "grouped-full-budget": "grouped $\\alpha{=}0.5$, 8,434 pairs, trained on 16 frames",
       "grouped-k16": "grouped $\\alpha{=}0.5$, 2,400 pairs, trained on 16 frames",
       "grouped-4800": "grouped $\\alpha{=}0.5$, 4,800 pairs", "two-stage": "two-stage"}


def sha16(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()[:16]


def g2(x):
    return PEND if x is None else ("0.00" if abs(x) < 0.005 else f"{x:+.2f}")


def ci(v, c, nd=2):
    return PEND if v is None else f"{v:+.{nd}f} [{c[0]:.{nd}f}, {c[1]:.{nd}f}]"


def label_of(k):
    fam, o, a, b, s, tr, ev = k
    if o == "grouped":
        lab = "grouped $\\alpha{=}%g$" % a + (", $\\beta{=}%g$" % b if b is not None and abs(b - 0.1) > 1e-9 else "")
    else:
        lab = OBJ.get(o, o)
        if o == "two-stage":
            lab += (", $\\alpha{=}%g$" % a if a is not None else "") + (", $\\beta{=}%g$" % b if b is not None and abs(b - 0.1) > 1e-9 else "")
    if s == 1:
        lab += " (second seed)"
    if tr == "t":
        lab += ", text-first"
    return FAMS[k[0]] + ", " + lab


def a3_key(p):
    fam, obj, lab = p.get("family"), p.get("objective"), p["label"]
    if obj in (None, "public-RL") or (obj or "").startswith("sft-shrink") or fam not in FAMS:
        return None
    m = re.search(r"_s(\d)(?=_|$)", lab)
    seed = int(m.group(1)) if m else None
    a, b = p.get("alpha"), p.get("beta")
    if obj == "sft":
        a, b = None, 0.0
    if obj == "iou-grpo":
        a = b = seed = None
    ev = "t" if "textfirst" in lab else "v"
    return M(fam, obj, a, b, seed, train="t" if _train_tf(lab) else "v", eval=ev)


def build_S15(C, out):
    p = os.path.join(ANA, "a3_scale.json")
    d = json.load(open(p, encoding="utf-8"))
    by = {}
    for x in d["pairs"]:
        k = a3_key(x)
        if k is not None:
            by.setdefault((k, x["dataset"]), []).append(x)
    L = ["% S15 -- generated by scripts/build_scale_newly_tables_v3.py (canonical_v3); do not edit by hand",
         "\\begin{table}[tbp]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}\\renewcommand{\\arraystretch}{1.04}",
         "\\caption{\\textbf{$\\Gamma$ does not follow the change in clean-video NLL.} Each row pairs a model with its base: our "
         "trained models, the three public checkpoints against the Qwen2.5-VL-7B base (the pairs of Table~\\ref{tab:audit}), and "
         "TimeLens-8B against Qwen3-VL-8B. All values use the mask operator on $H_\\cap$, the $n_\\cap$ questions both models "
         "localise. The columns give the clean-video negative log-likelihood (NLL) of the annotated answer in nats per token "
         "for the base and the trained model, then $\\Gm$, its sign fraction (the fraction of $H_\\cap$ on which $\\psi$ rises) "
         "and $\\Gamma_c$, the change in the bounded index $c=(\\dE-\\dO)/(|\\dE|+|\\dO|+0.05)$, with its 95\\% interval. Text-first "
         "rows put the query before the video.}",
         "\\label{tab:scale}", "\\begin{tabular}{@{}>{\\raggedright\\arraybackslash}p{5.6cm}ccccc@{}}", "\\toprule",
         "Configuration & $n_\\cap$ & clean NLL base / trained & $\\Gm$ & sign frac. & $\\Gamma_c$ \\\\", "\\midrule"]
    dsorder = ["charades-sta", "charades-timelens", "qvhighlights"]
    keys = sorted(by, key=lambda kd: (dsorder.index(kd[1]), list(FAMS).index(kd[0][0]), label_of(kd[0])))

    STA = []

    def public_rows():
        # the three public checkpoints against the Qwen base, same pairs as Table 1 (a3 env A/B; a6 node5)
        out = []
        for lab_a3, (lab, env) in PUBLIC_S15.items():
            hit = [x for x in d["pairs"] if x["label"] == lab_a3 and x["env"] == env]
            if len(hit) != 1:
                raise SystemExit(f"S15 public: {lab_a3} env {env} has {len(hit)} rows")
            out.append((lab, hit[0], p))
        p6 = os.path.join(ANA, "a6_vc_vs_qwen.json")
        d6 = json.load(open(p6, encoding="utf-8"))
        hit = [x for x in d6["pairs"] if "(node5) vs" in x["label"]]
        if len(hit) != 1:
            raise SystemExit("S15 public: a6 node5 pair missing")
        out.append(("VideoChat-R1 (public)", hit[0], p6))
        # 09-25: TimeLens-8B against its own base, Qwen3-VL-8B (not a pair of Table 1)
        hit = [x for x in d["pairs"] if x["label"] == "TimeLens-8B(public) vs Qwen3-VL-8B"]
        if len(hit) != 1:
            raise SystemExit("S15 public: TimeLens-8B vs Qwen3-VL-8B pair missing")
        out.append(("TimeLens-8B (public) against Qwen3-VL-8B", hit[0], p))
        for lab, x, src in out:
            m = x["mask"]
            C.sources.append({"table": "S15", "row": lab, "src_file": os.path.basename(src), "sha16": sha16(src),
                              "a3_label": x["label"], "arm": x.get("arm"), "base": x.get("base")})
            STA.append((lab, x["nll_arm"] - x["nll_base"], m["gamma"], m["sign_frac"], m["gamma_c"]))
            L.append(" & ".join([lab, str(x["n_H_int"]), f"{x['nll_base']:.2f} / {x['nll_arm']:.2f}", g2(m["gamma"]),
                                 f"{m['sign_frac']:.2f}", ci(m["gamma_c"], m["gamma_c_ci95"])]) + " \\\\")

    cur = None
    for k, ds in keys:
        if ds != cur:
            if cur == "charades-sta":
                public_rows()
            L.append("\\addlinespace[1pt]\\multicolumn{6}{@{}l}{\\textit{%s}} \\\\" % {"charades-sta": "Charades-STA", "charades-timelens": "Charades, TimeLens labels", "qvhighlights": "QVHighlights"}[ds])
            cur = ds
        env = C.env_for(k, "gamma", ds)
        C.ctx("S15", f"{label_of(k)} / {ds} / env {env}")
        hit = [x for x in by[(k, ds)] if x["env"] == env]
        if len(hit) > 1:
            raise SystemExit(f"S15: {key_str(k)} {ds} {env} has {len(hit)} rows")
        if not hit:
            C.log_pending("whole row", "gamma", k, ds, env, "a3 only has " + ",".join(x["env"] for x in by[(k, ds)]) + " rows")
            L.append(label_of(k) + " & " + " & ".join([PEND] * 5) + " \\\\")
            continue
        x = hit[0]
        m = x["mask"]
        if ds == "charades-sta":
            STA.append((label_of(k), x["nll_arm"] - x["nll_base"], m["gamma"], m["sign_frac"], m["gamma_c"]))
        C.sources.append({"table": "S15", "row": label_of(k), "env": env, "src_file": os.path.basename(p), "sha16": sha16(p),
                          "a3_label": x["label"], "arm": x.get("arm"), "base": x.get("base")})
        L.append(" & ".join([label_of(k), str(x["n_H_int"]), f"{x['nll_base']:.2f} / {x['nll_arm']:.2f}", g2(m["gamma"]),
                             f"{m['sign_frac']:.2f}", ci(m["gamma_c"], m["gamma_c_ci95"])]) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}", f"% source: {os.path.basename(p)} {sha16(p)}"]
    open(out, "w", encoding="utf-8", newline="\n").write(emph("\n".join(L) + "\n", os.path.basename(out)[:-4]))
    from scipy.stats import spearmanr
    g = [r[2] for r in STA]
    corr = {"n_configs": len(STA), "dataset": "charades-sta", "operator": "mask",
            "spearman_gamma_vs_dnll": spearmanr(g, [r[1] for r in STA])[0],
            "spearman_gamma_vs_signfrac": spearmanr(g, [r[3] for r in STA])[0],
            "spearman_gamma_vs_gammac": spearmanr(g, [r[4] for r in STA])[0],
            "rows": [dict(zip(("label", "d_nll", "gamma", "sign_frac", "gamma_c"), r)) for r in STA]}
    json.dump(corr, open(os.path.join(os.path.dirname(out), "S15_correlations.json"), "w", encoding="utf-8"), indent=1)
    print("S15 correlations:", {k: (round(v, 3) if isinstance(v, float) else v) for k, v in corr.items() if k != "rows"})


A2MAP = {"Qwen7B pure SFT": M(Q7, "sft", None, 0.0, 0), "Qwen7B IoU-GRPO": M(Q7, "iou-grpo"),
         "Qwen7B grouped a=0.25": M(Q7, "grouped", 0.25, 0.1, 0), "Qwen7B grouped a=0.5": M(Q7, "grouped", 0.5, 0.1, 0),
         "Qwen7B grouped a=1.0 s0": M(Q7, "grouped", 1.0, 0.1, 0), "Qwen7B grouped a=1.0 s1": M(Q7, "grouped", 1.0, 0.1, 1)}
PUBLIC_S15 = {"TimeZero(public RL) vs Qwen": ("TimeZero (public)", "A"),
              "Time-R1(public RL) vs Qwen": ("Time-R1 (public)", "B")}
PUBLIC = {"TimeZero (public RL) vs Qwen": ("TimeZero (public)", "A"),
          "Time-R1 (public RL) vs Qwen": ("Time-R1 (public)", "B")}


def build_S16(C, out):
    p = os.path.join(ANA, "a2_newly_correct.json")
    d = json.load(open(p, encoding="utf-8"))
    groups = {}
    for c in d["configs"]:
        groups.setdefault(c["label"], []).append(c)
    L = ["% S16 -- generated by scripts/build_scale_newly_tables_v3.py (canonical_v3); do not edit by hand",
         "\\begin{table}[t]", "\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}\\renewcommand{\\arraystretch}{1.04}",
         "\\caption{\\textbf{$\\psi$ on the newly correct questions stays within $0.1$ nats per token of the base's after accuracy "
         "training and far exceeds it after placebo-controlled training.} All values come from the likelihood audit with the "
         "mask operator on 200 questions and are in nats per token. $|\\mathrm{NC}|$ is the number of questions the trained "
         "model localises and its base does not, and $\\psi^{\\mathrm{trained}}(\\mathrm{NC})$ is the trained model's $\\psi$ on "
         "them. $\\psi^{\\mathrm{base}}$ is the base's $\\psi$ on the questions the base localises, in the audit paired with that "
         "model. The column \\emph{difference} is the first minus the second; the two sets are not paired, and brackets give "
         "95\\% intervals.}",
         "\\label{tab:newly_psi}", "\\begin{tabular}{@{}lcccc@{}}", "\\toprule",
         "Configuration & $|\\mathrm{NC}|$ & $\\psi^{\\mathrm{trained}}(\\mathrm{NC})$ & $\\psi^{\\mathrm{base}}$ (base hits) & difference \\\\", "\\midrule"]
    for lab, cs in groups.items():
        if lab in A2MAP:
            k = A2MAP[lab]
            env = C.env_for(k, "gamma", "charades-sta")
            name = label_of(k)
        elif lab in PUBLIC:
            name, env = PUBLIC[lab]
            k = None
        else:
            continue
        C.ctx("S16", f"{name} / env {env}")
        hit = [c for c in cs if c["env"] == env]
        if not hit:
            if k is not None:
                C.log_pending("whole row", "gamma", k, "charades-sta", env, "a2 only has " + ",".join(c["env"] for c in cs) + " rows")
            L.append(name + " & " + " & ".join([PEND] * 4) + " \\\\")
            continue
        c = hit[0]
        m = c["mask"]
        C.sources.append({"table": "S16", "row": name, "env": env, "src_file": os.path.basename(p), "sha16": sha16(p), "arm": c["arm"], "base": c["base"]})
        L.append(" & ".join([name, str(c["n_NC"]), ci(m["psi_arm_NC"], m["psi_arm_NC_ci95"]),
                             ci(m["psi_base_basehits"], m["psi_base_basehits_ci95"]),
                             ci(m["diff_NC_minus_basehits"], m["diff_NC_minus_basehits_ci95"])]) + " \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}", f"% source: {os.path.basename(p)} {sha16(p)}"]
    open(out, "w", encoding="utf-8", newline="\n").write(emph("\n".join(L) + "\n", os.path.basename(out)[:-4]))


def main():
    C = Canon()
    build_S15(C, os.path.join(T, "S15_scale.tex"))
    build_S16(C, os.path.join(T, "S16_newly_psi.tex"))
    os.makedirs(LOGD, exist_ok=True)
    json.dump({"sources": C.sources, "pending": C.pending}, open(os.path.join(LOGD, "build_scale_newly_tables_v3.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1, default=str)
    print("S15/S16 written; pending", len(C.pending))


if __name__ == "__main__":
    main()
