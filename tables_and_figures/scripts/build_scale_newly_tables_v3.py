"""build_scale_newly_tables_v3.py -- S15 (tab:scale) and S16 (tab:newly_psi) under canonical_v3 (2026-09-23).

S15: rows of analysis/a3_scale.json whose (configuration, environment) is the canonical environment of that
     configuration's 14Ln gamma on the same dataset (canonical_v3.env_for(k, "gamma", dataset)).
S16: configs of analysis/a2_newly_correct.json likewise (mask operator).  The two public-checkpoint rows follow
     the environments fixed for Table 1 (TimeZero: A, Time-R1: B).
Rows whose canonical environment has no row in the analysis product are printed as \\pending and logged.
"""
