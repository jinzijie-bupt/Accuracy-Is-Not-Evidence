"""build_query_spec_table_v2.py (2026-09-23; canonical_v2 copy of build_query_spec_table_v1.py)

v2: a row prints only when its qswap3 product sits in the configuration's canonical environment
(canonical_v3); otherwise the row is pending and logged in tables/_v3_logs/build_query_spec_table_v3.json.

v1 docstring:

Generates tables/S11_query_specificity.tex from the r3 query-swap reader products in
results/judgment_20260922/qswap3_*.json (reader read_14Lqn_v2, instrument
14Lqn_native_query_swap_probe_r3 -- the pre-registered successor of the invalidated first
revision; see the instruments paragraph of Appendix A).

Two readouts per pair, both mask-operator, token-mean nats, same-machine pairing:
  spec: the 2x2 cross design.  psi_own  = own-query contrast (edit E*_i vs edit E_j),
        psi_cross = the same under the partner query;  Gamma_spec = d(psi_own) - d(psi_cross).
  old:  placebo-pool decomposition on T \\ (E*_i u E_j): Gamma = Gamma_agnostic + Gamma_sem.
The table is generated, never hand-edited.
"""
import os as _os_supp
_SUPP = _os_supp.path.abspath(_os_supp.path.join(_os_supp.path.dirname(_os_supp.path.abspath(__file__)), "..", "..")).replace("\\", "/")
import json, os, hashlib
import sys as _sys, os as _os
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
from canonical_v3 import Canon, M, key_str, Q7, Q3, TZ, TR, VC, TL, PEND as _PEND  # canonical_v2

ROOT = _SUPP + r"/results/judgment_20260922"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tables", "S11_query_specificity.tex")

ROWS = [
    ("Qwen2.5-VL-7B",  [("grouped $\\alpha{=}0.25$",                    "natbase_a025_vs_base_node1"),
                        ("grouped $\\alpha{=}0.5$",                     "natbase_a05_tf5_vs_base_node2"),
                        ("grouped $\\alpha{=}0.5$, $\\beta{=}0.03$",    "natbase_a05_b003_vs_base_node2"),
                        ("grouped $\\alpha{=}1$",                       "natbase_a10_s0_vs_base_node2"),
                        ("grouped $\\alpha{=}1$ (second seed)",         "natbase_a10_s1_vs_base_node2"),
                        ("two-stage, $\\alpha{=}0.5$",                  "natsft2g_a05_vs_base_node1"),
                        ("two-stage, $\\beta{=}0.03$",                  "natsft2g_b003_vs_base_node1"),
                        ("evidence margin only",                        "abl_single_vs_base_node1"),
                        ("SFT",                                         "natsft_b0_tf5_vs_base_node1")]),
    ("TimeZero",       [("grouped $\\alpha{=}0.25$",                    "nattz_a025_vs_tzbase_node2"),
                        ("grouped $\\alpha{=}0.5$",                     "nattz_a05_vs_tzbase_node2"),
                        ("grouped $\\alpha{=}0.5$, text-first",         "nattz_a05_tf_vs_tzbase_tf_node5")]),
    ("Time-R1",        [("grouped $\\alpha{=}0.25$",                    "nattr1_a025_vs_tr1base_node4")]),
    ("VideoChat-R1",   [("grouped $\\alpha{=}0.25$",                    "natvc_a025_vs_vcbase_node4"),
                        ("grouped $\\alpha{=}0.5$",                     "natvc_a05_vs_vcbase_node4"),
                        ("grouped $\\alpha{=}0.5$, text-first",         "natvc_a05_tf_vs_vcbase_tf_node5")]),
]

def sha16(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()[:16]

L = []
L.append("% AUTO-GENERATED by scripts/build_query_spec_table_v3.py (canonical_v3) -- do not edit by hand.")
L.append("\\begin{table}[tb]")
L.append("\\centering\\scriptsize")
L.append("\\caption{\\textbf{The audited contrast moves with the query: $\\Gamma_{\\mathrm{spec}}$ is positive in every grouped "
         "model and zero in SFT.} All values use the mask operator and are in nats per token; Appendix~\\ref{app:qspec} defines "
         "them. The left block uses the $n$ questions that both models localise and that have a partner event, another "
         "annotated event of the same video. The partner contrast scores the question's own interval and is the likelihood drop "
         "when its event's frames are masked minus the drop when the partner event's frames are masked. The left block gives "
         "the trained-minus-base change of this contrast under the question's own query ($\\Delta\\psi_{\\mathrm{own}}$) and under "
         "the partner event's query ($\\Delta\\psi_{\\mathrm{cross}}$), and "
         "$\\Gamma_{\\mathrm{spec}}=\\Delta\\psi_{\\mathrm{own}}-\\Delta\\psi_{\\mathrm{cross}}$ with the fraction of questions on "
         "which it is positive. The right block draws the placebo from outside both events, which leaves out 8 to 11 of these "
         "questions per row, and splits $\\Gamma$ into the part that remains under the partner event's query ($\\Gamma_{\\mathrm{agn}}$) "
         "and the rest ($\\Gamma_{\\mathrm{sem}}=\\Gamma-\\Gamma_{\\mathrm{agn}}$). Brackets give 95\\% intervals, and text-first "
         "rows put the query before the video.}")
L.append("\\label{tab:s11}")
L.append("\\setlength{\\tabcolsep}{2.2pt}\\renewcommand{\\arraystretch}{1.04}")
L.append("\\begin{tabular}{@{}lrcccc@{\\hspace{7pt}}ccc@{}}")
L.append("\\toprule")
L.append(" & & \\multicolumn{4}{c}{Query crossed} & \\multicolumn{3}{c@{}}{Placebo pool split} \\\\")
L.append("\\cmidrule(lr){3-6}\\cmidrule(l){7-9}")
L.append(" & $n$ & $\\Delta\\psi_{\\mathrm{own}}$ & $\\Delta\\psi_{\\mathrm{cross}}$ & "
         "$\\Gamma_{\\mathrm{spec}}$ & \\shortstack{sign\\\\frac.} & $\\Gamma$ & $\\Gamma_{\\mathrm{agn}}$ & $\\Gamma_{\\mathrm{sem}}$ \\\\")
srcs = []
CAN = Canon()
os.makedirs(os.path.join(os.path.dirname(OUT), "_v3_logs"), exist_ok=True)
for fam, arms in ROWS:
    L.append("\\midrule")
    L.append("\\multicolumn{9}{@{}l}{\\emph{%s}} \\\\" % fam)
    for label, tag in arms:
        p = os.path.join(ROOT, "qswap3_%s.json" % tag)
        k = [x[2] for x in CAN.ext if x[0] == "qswap" and x[5]["tag"] == tag][0]
        CAN.ctx("S11", "%s / %s / %s" % (fam, label, key_str(k)))
        hit = CAN.ext_pick("qswap", k, column="whole row")
        if hit is None:
            L.append("\\quad %s & %s \\\\" % (label, " & ".join([_PEND] * 8)))
            srcs.append("qswap3_%s.json NOT-CANONICAL(canonical env %s)" % (tag, CAN.env(k)))
            continue
        p = hit[4]
        d = json.load(open(p, encoding="utf-8"))
        s = d["mask"]["spec"]["vs_base"]; o = d["mask"]["old"]["vs_base"]
        srcs.append("%s %s" % (os.path.basename(p), sha16(p)))
        L.append("\\quad %s & %d & $%+.2f$ & $%+.2f$ & $%+.2f$ [%.2f, %.2f] & %.2f & $%+.2f$ & $%+.2f$ [%.2f, %.2f] & $%+.2f$ \\\\" % (
            label, s["n"], s["d_psi_own"], s["d_psi_cross"],
            s["gamma_spec"], s["gamma_spec_ci"][0], s["gamma_spec_ci"][1], s["pos_frac"],
            o["gamma"], o["gamma_agnostic"], o["gamma_agnostic_ci"][0], o["gamma_agnostic_ci"][1], o["gamma_sem"]))
L.append("\\bottomrule")
L.append("\\end{tabular}")
L.append("\\end{table}")
L.append("% sources: " + "; ".join(srcs))
from table_emph_v3 import emph  # noqa: E402  (bold: the entries discussed in the text; located by row label and column)
open(OUT, "w", encoding="utf-8").write(emph("\n".join(L) + "\n", "S11_query_specificity"))
json.dump({"sources": CAN.sources, "pending": CAN.pending}, open(os.path.join(os.path.dirname(OUT), "_v3_logs", "build_query_spec_table_v3.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1, default=str)
print("[qspec] wrote", os.path.normpath(OUT), "rows:", sum(len(a) for _, a in ROWS))
