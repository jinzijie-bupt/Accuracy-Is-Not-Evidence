import os as _os_supp
_SUPP = _os_supp.path.abspath(_os_supp.path.join(_os_supp.path.dirname(_os_supp.path.abspath(__file__)), "..", "..")).replace("\\", "/")
import io, json, os
import sys as _sys, os as _os
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
from canonical_v3 import Canon, M, key_str, Q7, Q3, TZ, TR, VC, TL, PEND as _PEND  # canonical_v2

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = _SUPP + "/results/judgment_20260923/newly_correct_v1.json"
d = json.load(io.open(SRC, encoding="utf-8"))

# round 2 : percentages with one decimal, intervals in the grey \ci format (no % inside), missing = \NA
def pct(x): return "%.1f" % (100 * x)
def pctci(e): return "%s [%s, %s]" % (pct(e["rate"]), pct(e["ci"][0]), pct(e["ci"][1]))

ROWS = [
    ("iou_grpo_envB", "IoU-GRPO"),
    ("grouped_a05_envA", "grouped $\\alpha{=}0.5$"),
    ("grouped_a10_envA", "grouped $\\alpha{=}1$"),
]
L = ["% S12 -- generated by scripts/build_newly_correct_table_v3.py (canonical_v3) from newly_correct_v1.json",
     "\\begin{table}[t]",
     "\\centering\\scriptsize\\setlength{\\tabcolsep}{3pt}\\renewcommand{\\arraystretch}{1.04}",   # as S16 next to it (2026-09-24; \\papertablestyle ran 12pt wide)
     "\\caption{\\textbf{Most of IoU-GRPO's newly correct answers survive masking as many placebo frames, and most are lost "
     "when the evidence frames are masked.} $|\\mathrm{NC}|$ is the number of questions a trained model localises on the "
     "clean video and its base does not. The other columns give the percentage of that set that the constant $(0,10)$\\,s "
     "window also solves (on all questions it solves $32\\%$), that stays correct on an all-black video, and that stays "
     "correct when regenerated with the evidence frames or as many placebo frames masked. The last two columns are given "
     "for IoU-GRPO only, on the 181 of its newly correct questions that are among the 1{,}000 questions of the behavioural "
     "audit. Brackets give 95\\% intervals.}",
     "\\label{tab:s12}",
     "\\begin{tabular}{@{}lccccc@{}}",
     "\\toprule",
     "Objective & $|\\mathrm{NC}|$ & const-win (\\%) & black (\\%) & evid-mask (\\%) & placebo-mask (\\%) \\\\",
     "\\midrule"]
CAN = Canon()
for key, lab in ROWS:
    k = [x[2] for x in CAN.ext if x[0] == "newly" and x[5]["key"] == key][0]
    CAN.ctx("S12", "%s / %s" % (lab, key_str(k)))
    if CAN.ext_pick("newly", k, column="whole row", key=key) is None:
        L.append("%s & %s \\\\" % (lab, " & ".join([_PEND] * 5)))
        continue
    v = d[key]
    n = v["n_newly_correct"]
    cw = pctci(v["cw_solvable_on_newly"])
    bl = pctci(v["black_retained_on_newly"]) if "black_retained_on_newly" in v else "\\NA"
    ev = pctci(v["evidence_mask_retained_on_newly_n1000"]) if "evidence_mask_retained_on_newly_n1000" in v else "\\NA"
    pl = pctci(v["placebo_mask_retained_on_newly_n1000"]) if "placebo_mask_retained_on_newly_n1000" in v else "\\NA"
    L.append("%s & %d & %s & %s & %s & %s \\\\" % (lab, n, cw, bl, ev, pl))
L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
out = os.path.join(ROOT, "tables", "S12_newly_correct.tex")
from table_emph_v3 import emph  # noqa: E402  (bold: the entries discussed in the text; located by row label and column)
with io.open(out, "w", encoding="utf-8") as f:
    f.write(emph("\n".join(L) + "\n", "S12_newly_correct"))
os.makedirs(os.path.join(ROOT, "tables", "_v3_logs"), exist_ok=True)
json.dump({"sources": CAN.sources, "pending": CAN.pending}, io.open(os.path.join(ROOT, "tables", "_v3_logs", "build_newly_correct_table_v3.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1, default=str)
print("WROTE", out)
