"""build_order_table_v2.py -- (2026-09-23; canonical_v2 copy of v1; output goes to the rebuild copy).
v2: every row is a base configuration; the table is written only if every base's canonical
environment is B (the node3 runs), otherwise it stops (rule R4 layout decision for the author).
v1: build_order_table_v1.py -- S13: the four-base two-order message-order matrix.
Source: the 16 node3 single-stack full-split runs (12p4n_r6),
results/native_eval_20260918_node3/p4nat_{base}_{style}[_textfirst]_{tf5meta|black}_node3_full.json.
Columns per (base, order): clean R@0.5, paired dR@0.5 (text-first minus video-first, 95% video-cluster
bootstrap over the same 3,720 questions), black answering rate, black R@0.5.
Self-check: every file must have 3,720 rows and the two orders of one base must share the qid set.
"""
import os as _os_supp
_SUPP = _os_supp.path.abspath(_os_supp.path.join(_os_supp.path.dirname(_os_supp.path.abspath(__file__)), "..", "..")).replace("\\", "/")
import json, os, random, hashlib
import sys as _sys, os as _os
_sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
from canonical_v3 import Canon, M, key_str, Q7, Q3, TZ, TR, VC, TL, PEND as _PEND  # canonical_v2

D = _SUPP + r"/results/native_eval_20260918_node3"
OUT = _os.path.join(_os.path.dirname(_os.path.dirname(_os.path.abspath(__file__))), "tables", "S13_message_order.tex")
SRC = _os.path.join(_os.path.dirname(OUT), "S13_SOURCES.json")
assert "_iclr2027" not in OUT.replace(chr(92), "/")
BASES = [("Qwen2.5-VL-7B", "qwenbase", "timer1_default", "video-first"),
         ("TimeZero", "tzbase", "timer1_default", "text-first"),
         ("Time-R1", "tr1base", "timer1_default", "video-first"),
         ("VideoChat-R1", "vcbase", "vchat", "text-first")]  # 09-25: VideoChat-R1's released eval code is text-first (VERIFICATION_JOURNAL L1440)
B = 2000
random.seed(20260923)


def iou(p, g):
    if not p: return 0.0
    s1, e1 = float(p[0]), float(p[1]); s2, e2 = g
    inter = max(0.0, min(e1, e2) - max(s1, s2)); union = max(e1, e2) - min(s1, s2)
    return inter / union if union > 0 else 0.0


def load(f):
    p = os.path.join(D, f)
    rows = json.load(open(p, encoding="utf-8"))
    assert len(rows) == 3720, (f, len(rows))
    sha = hashlib.sha256(open(p, "rb").read()).hexdigest()[:16]
    return rows, sha


def hits(rows):
    return {r["qid"]: (iou(r.get("pred"), (float(r["gsA"]), float(r["geA"]))) >= 0.5, r["video"]) for r in rows}


def paired_ci(hv, ht):
    qids = sorted(hv)
    assert set(hv) == set(ht)
    byvid = {}
    for q in qids:
        byvid.setdefault(hv[q][1], []).append(int(ht[q][0]) - int(hv[q][0]))
    vids = sorted(byvid)
    point = sum(sum(v) for v in byvid.values()) / len(qids) * 100
    bs = []
    for _ in range(B):
        s = [byvid[random.choice(vids)] for _ in vids]
        n = sum(len(x) for x in s)
        bs.append(sum(sum(x) for x in s) / n * 100)
    bs.sort()
    return point, bs[int(0.025 * B)], bs[int(0.975 * B)]


def main():
    L = ["% generated by scripts/build_order_table_v3.py (canonical_v3) -- do not edit by hand",
         "\\begin{table}[t]", "\\centering\\papertablestyle",
         "\\caption{\\textbf{Message order moves base models in family-specific directions, and it also moves their accuracy on a "
         "black video.} Each base model is evaluated under both message orders, with the video first (video-first) or the query "
         "text first (text-first), and everything else identical. $\\Delta$\\Rfive{} is text-first minus video-first, paired per "
         "question, in points, with its 95\\% interval; \\emph{black ans.} and \\emph{black \\Rfive{}} are the answering rate and "
         "the accuracy on all-black videos under the same order. A $^{\\circ}$ marks the order the checkpoint ships with.}",
         "\\label{tab:s13}",
         "\\begin{tabular}{@{}llcccc@{}}", "\\toprule",
         "Model & order & \\Rfive{} & $\\Delta$\\Rfive{} & black ans. & black \\Rfive{} \\\\", "\\midrule"]
    src = {}
    CAN = Canon()
    FAMK = {"qwenbase": Q7, "tzbase": TZ, "tr1base": TR, "vcbase": VC}
    for disp, base, style, official in BASES:
        for o in ("v", "t"):
            CAN.ctx("S13", "%s / %s" % (disp, o))
            hit = CAN.ext_pick("order", M(FAMK[base], "base", eval=o), column="clean+black")
            assert hit is not None, ("S13: base canonical env is not B -- rule R4 layout decision", disp, o)
        cv, s1 = load(f"p4nat_{base}_{style}_tf5meta_node3_full.json")
        ct, s2 = load(f"p4nat_{base}_{style}_textfirst_tf5meta_node3_full.json")
        bv, s3 = load(f"p4nat_{base}_{style}_black_node3_full.json")
        bt, s4 = load(f"p4nat_{base}_{style}_textfirst_black_node3_full.json")
        src[base] = dict(clean_v=s1, clean_t=s2, black_v=s3, black_t=s4)
        hv, ht = hits(cv), hits(ct)
        acc_v = sum(h for h, _ in hv.values()) / 3720
        acc_t = sum(h for h, _ in ht.values()) / 3720
        d, lo, hi = paired_ci(hv, ht)
        ba_v = sum(1 for r in bv if r.get("pred")) / 3720
        ba_t = sum(1 for r in bt if r.get("pred")) / 3720
        br_v = sum(iou(r.get("pred"), (float(r["gsA"]), float(r["geA"]))) >= 0.5 for r in bv) / 3720
        br_t = sum(iou(r.get("pred"), (float(r["gsA"]), float(r["geA"]))) >= 0.5 for r in bt) / 3720
        mv = "$^{\\circ}$" if official == "video-first" else ""
        mt = "$^{\\circ}$" if official == "text-first" else ""
        L.append(f"{disp} & video-first{mv} & {acc_v:.3f} & \\NA & {ba_v:.3f} & {br_v:.3f} \\\\")
        L.append(f"\\quad & text-first{mt} & {acc_t:.3f} & {d:+.1f} [{lo:.1f}, {hi:.1f}] & {ba_t:.3f} & {br_t:.3f} \\\\")
        L.append("\\addlinespace[2pt]")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    from table_emph_v3 import emph   # bold: the entries discussed in the text (located by row label and column)
    open(OUT, "w", encoding="utf-8", newline="\n").write(emph("\n".join(L) + "\n", "S13_message_order"))
    json.dump(src, open(SRC, "w", encoding="utf-8"), indent=1)
    _os.makedirs(_os.path.join(_os.path.dirname(OUT), "_v3_logs"), exist_ok=True)
    json.dump({"sources": CAN.sources, "pending": CAN.pending}, open(_os.path.join(_os.path.dirname(OUT), "_v3_logs", "build_order_table_v3.json"), "w", encoding="utf-8"), ensure_ascii=False, indent=1, default=str)
    print("wrote", OUT)


if __name__ == "__main__":
    main()
